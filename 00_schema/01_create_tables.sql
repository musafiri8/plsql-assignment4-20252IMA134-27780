PROMPT Creating DEPARTMENTS table...
CREATE TABLE departments (
    dept_id          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 10) PRIMARY KEY,
    dept_code        VARCHAR2(10) NOT NULL UNIQUE,
    dept_name        VARCHAR2(100) NOT NULL,
    faculty_name     VARCHAR2(100) NOT NULL,
    created_at       DATE DEFAULT SYSDATE NOT NULL
);

PROMPT Creating COURSES table...
CREATE TABLE courses (
    course_id        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    course_code      VARCHAR2(15) NOT NULL UNIQUE,
    course_title     VARCHAR2(100) NOT NULL,
    credits          NUMBER(2) NOT NULL CHECK (credits BETWEEN 1 AND 6),
    dept_id          NUMBER NOT NULL,
    fee_per_credit   NUMBER(10,2) DEFAULT 50000.00 NOT NULL CHECK (fee_per_credit > 0),
    max_capacity     NUMBER(3) DEFAULT 35 NOT NULL CHECK (max_capacity > 0),
    status           VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_courses_dept FOREIGN KEY (dept_id) REFERENCES departments(dept_id)
);

PROMPT Creating STUDENTS table...
CREATE TABLE students (
    student_id       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1) PRIMARY KEY,
    student_reg_no   VARCHAR2(20) NOT NULL UNIQUE,
    first_name       VARCHAR2(50) NOT NULL,
    last_name        VARCHAR2(50) NOT NULL,
    email            VARCHAR2(100) NOT NULL UNIQUE,
    dept_id          NUMBER NOT NULL,
    enrollment_date  DATE DEFAULT SYSDATE NOT NULL,
    current_gpa      NUMBER(3,2) DEFAULT 0.00 NOT NULL CHECK (current_gpa BETWEEN 0.00 AND 4.00),
    balance_due      NUMBER(12,2) DEFAULT 0.00 NOT NULL,
    academic_status  VARCHAR2(20) DEFAULT 'GOOD_STANDING' NOT NULL 
                     CHECK (academic_status IN ('GOOD_STANDING', 'PROBATION', 'SUSPENDED', 'GRADUATED')),
    CONSTRAINT fk_students_dept FOREIGN KEY (dept_id) REFERENCES departments(dept_id)
);

PROMPT Creating ENROLLMENTS table...
CREATE TABLE enrollments (
    enrollment_id    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 5000 INCREMENT BY 1) PRIMARY KEY,
    student_id       NUMBER NOT NULL,
    course_id        NUMBER NOT NULL,
    semester         VARCHAR2(20) NOT NULL,
    academic_year    VARCHAR2(10) NOT NULL,
    midterm_score    NUMBER(5,2) CHECK (midterm_score IS NULL OR (midterm_score >= 0 AND midterm_score <= 40)),
    final_score      NUMBER(5,2) CHECK (final_score IS NULL OR (final_score >= 0 AND final_score <= 60)),
    total_score      NUMBER(5,2) CHECK (total_score IS NULL OR (total_score >= 0 AND total_score <= 100)),
    letter_grade     VARCHAR2(3) CHECK (letter_grade IS NULL OR letter_grade IN ('A', 'A-', 'B+', 'B', 'B-', 'C+', 'C', 'C-', 'D', 'F', 'I')),
    grade_point      NUMBER(3,2) CHECK (grade_point IS NULL OR (grade_point >= 0.00 AND grade_point <= 4.00)),
    enrollment_status VARCHAR2(15) DEFAULT 'ENROLLED' NOT NULL 
                     CHECK (enrollment_status IN ('ENROLLED', 'COMPLETED', 'DROPPED')),
    enrolled_at      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_enrollments_student FOREIGN KEY (student_id) REFERENCES students(student_id),
    CONSTRAINT fk_enrollments_course FOREIGN KEY (course_id) REFERENCES courses(course_id),
    CONSTRAINT uk_student_course_sem UNIQUE (student_id, course_id, semester, academic_year)
);

PROMPT Creating GRADE_AUDIT_LOG table...
CREATE TABLE grade_audit_log (
    audit_id         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    enrollment_id    NUMBER NOT NULL,
    old_total_score  NUMBER(5,2),
    new_total_score  NUMBER(5,2),
    old_letter_grade VARCHAR2(3),
    new_letter_grade VARCHAR2(3),
    changed_by       VARCHAR2(50) DEFAULT USER NOT NULL,
    change_date      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    remarks          VARCHAR2(255),
    CONSTRAINT fk_audit_enrollment FOREIGN KEY (enrollment_id) REFERENCES enrollments(enrollment_id)
);

PROMPT Creating STUDENT_FINANCIAL_LOG table...
CREATE TABLE student_financial_log (
    txn_id           NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    student_id       NUMBER NOT NULL,
    course_id        NUMBER,
    txn_type         VARCHAR2(25) NOT NULL 
                     CHECK (txn_type IN ('TUITION_CHARGE', 'PAYMENT', 'SCHOLARSHIP_DISCOUNT', 'FEE_WAIVER')),
    amount           NUMBER(12,2) NOT NULL,
    txn_date         DATE DEFAULT SYSDATE NOT NULL,
    description      VARCHAR2(255),
    CONSTRAINT fk_fin_student FOREIGN KEY (student_id) REFERENCES students(student_id),
    CONSTRAINT fk_fin_course FOREIGN KEY (course_id) REFERENCES courses(course_id)
);

